#!/usr/bin/env python3
"""Build data/i5.js from the route anchors and the researched content.

Inputs:
  tools/anchors.json        [[exit_number, lat, lon], ...] from OpenStreetMap exit nodes
  content/seg-*.json        researched places, zones and trivia (one file per stretch)
Output:
  data/i5.js                window.I5DATA = {...}

Run:  python3 tools/build.py
"""
import glob, json, math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATS = {"farm", "hist", "nature", "town", "stop", "odd"}


def miles(a, b):
    R = 3958.8
    la1, lo1, la2, lo2 = map(math.radians, (a[1], a[2], b[1], b[2]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


def clean_route(pts):
    """Drop anchors that disagree wildly with both neighbours (bad OSM refs)."""
    pts = sorted(pts)
    changed = True
    while changed:
        changed = False
        for i, p in enumerate(pts):
            nbrs = [pts[j] for j in (i - 1, i + 1) if 0 <= j < len(pts)]
            if all(miles(p, q) > 3 * abs(p[0] - q[0]) + 5 for q in nbrs):
                print(f"  dropping bad anchor exit {p[0]}", file=sys.stderr)
                pts.pop(i)
                changed = True
                break
    return pts


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40]


def main():
    route = clean_route(json.load(open(os.path.join(ROOT, "tools", "anchors.json"))))
    # extend the first anchor back to mile 0 (the border) along the first segment's line
    (m0, a0, o0), (m1, a1, o1) = route[0], route[1]
    if m0 > 0:
        k = m0 / (m1 - m0)
        route.insert(0, [0, round(a0 - (a1 - a0) * k, 5), round(o0 - (o1 - o0) * k, 5)])
    places, zones, trivia = [], [], []
    files = sorted(glob.glob(os.path.join(ROOT, "content", "seg-*.json")))
    if not files:
        sys.exit("no content/seg-*.json files found")
    for f in files:
        d = json.load(open(f))
        for p in d.get("places", []):
            if p.get("cat") not in CATS:
                p["cat"] = "odd"
            p["mi"] = int(round(float(p["mi"])))
            p["side"] = p.get("side") if p.get("side") in ("E", "W") else None
            places.append({k: p.get(k) for k in ("mi", "name", "cat", "side", "visible", "where", "text", "src")})
        zones += d.get("zones", [])
        trivia += d.get("trivia", [])

    # de-duplicate places that two stretches both covered
    seen, uniq = set(), []
    for p in sorted(places, key=lambda p: p["mi"]):
        key = slug(p["name"])
        if key in seen:
            continue
        seen.add(key)
        p["id"] = f'{p["mi"]}-{key}'
        uniq.append(p)

    zones = sorted(zones, key=lambda z: z["from"])
    trivia = [t for t in trivia if isinstance(t.get("answer"), int) and len(t.get("choices", [])) >= 2]

    out = {"route": route, "places": uniq, "zones": zones, "trivia": trivia}
    with open(os.path.join(ROOT, "data", "i5.js"), "w") as fh:
        fh.write("// Generated by tools/build.py. Do not edit by hand.\n")
        fh.write("window.I5DATA=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"route {len(route)} anchors, {len(uniq)} places, {len(zones)} zones, {len(trivia)} trivia")


if __name__ == "__main__":
    main()
